CREATE TABLE IF NOT EXISTS tickets (
 id CHAR(36) NOT NULL PRIMARY KEY,
 owner VARCHAR(191) NOT NULL,
 booking_reference VARCHAR(100) NOT NULL DEFAULT '',
 ticket_number VARCHAR(100) NOT NULL DEFAULT '',
 passenger_name TEXT NOT NULL,
 passport VARCHAR(40) NOT NULL DEFAULT '',
 airline VARCHAR(200) NOT NULL DEFAULT '',
 departure_date DATE NULL,
 arrival_date DATE NULL,
 origin VARCHAR(200) NOT NULL DEFAULT '',
 destination VARCHAR(200) NOT NULL DEFAULT '',
 data LONGTEXT NOT NULL,
 filename VARCHAR(1000) NOT NULL,
 mime VARCHAR(100) NOT NULL,
 original_data LONGBLOB NOT NULL,
 file_hash CHAR(64) NOT NULL,
 reviewed TINYINT NOT NULL DEFAULT 0,
 created VARCHAR(30) NOT NULL,
 updated VARCHAR(30) NOT NULL,
 version INT NOT NULL DEFAULT 1,
 INDEX tickets_owner_updated (owner,updated),
 INDEX tickets_owner_passport (owner,passport),
 INDEX tickets_owner_booking (owner,booking_reference),
 UNIQUE KEY tickets_owner_file (owner,file_hash)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
