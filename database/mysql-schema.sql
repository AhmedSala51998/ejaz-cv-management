SET NAMES utf8mb4;
CREATE TABLE IF NOT EXISTS registry (
 id VARCHAR(36) PRIMARY KEY, owner VARCHAR(128) NOT NULL, passport VARCHAR(32) NOT NULL,
 name VARCHAR(2000) NOT NULL, created VARCHAR(32) NOT NULL,
 UNIQUE KEY registry_owner_passport(owner,passport)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS records (
 id VARCHAR(36) PRIMARY KEY, owner VARCHAR(128) NOT NULL, passport VARCHAR(32) NOT NULL,
 name VARCHAR(2000) NOT NULL, nationality VARCHAR(255) NOT NULL, data LONGTEXT NOT NULL,
 source VARCHAR(255) NOT NULL, filename VARCHAR(1000) NOT NULL, photo VARCHAR(255),
 created VARCHAR(32) NOT NULL, updated VARCHAR(32) NOT NULL, version INT NOT NULL DEFAULT 1,
 UNIQUE KEY records_owner_passport(owner,passport)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS history (
 id VARCHAR(36) PRIMARY KEY, owner VARCHAR(128) NOT NULL, record_id VARCHAR(36) NOT NULL,
 data LONGTEXT NOT NULL, source VARCHAR(255) NOT NULL, photo VARCHAR(255), created VARCHAR(32) NOT NULL,
 KEY history_owner_record(owner,record_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS photos (
 id VARCHAR(36) PRIMARY KEY, owner VARCHAR(128) NOT NULL, mime VARCHAR(100) NOT NULL,
 data MEDIUMBLOB NOT NULL, created VARCHAR(32) NOT NULL, KEY photos_owner(owner)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS uploaded_files (
 file_key VARCHAR(255) PRIMARY KEY, mime VARCHAR(150) NOT NULL, data LONGBLOB NOT NULL, created VARCHAR(32) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS login_attempts (
 ip_hash CHAR(64) PRIMARY KEY, attempts INT NOT NULL DEFAULT 0, window_until BIGINT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
